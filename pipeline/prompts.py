def format_prompt(template: str, **kwargs) -> str:
    """Заменя САМО точно {key} за известните kwargs."""
    if not kwargs:
        return template
    pattern = re.compile(r'\{(' + '|'.join(re.escape(k) for k in kwargs) + r')\}')
    return pattern.sub(lambda m: str(kwargs[m.group(1)]), template)


